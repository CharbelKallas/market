-- Initial schema. Written to run on PostgreSQL and on H2 in PostgreSQL mode (used by the tests).
-- Hibernate only validates the schema (ddl-auto=validate); every change goes in a new V<n>__*.sql file.

create table "user" (
    user_id                 bigint generated by default as identity primary key,
    username                varchar(255) not null,
    email                   varchar(255),
    password                varchar(255) not null,
    first_name              varchar(255),
    last_name               varchar(255),
    mobile_number           varchar(255),
    verified_date           timestamp,
    token_version           integer not null default 0,
    failed_signin_attempts  integer not null default 0,
    locked_until            timestamp,
    bootstrap_password_hash varchar(255),
    constraint uk_user_username unique (username),
    constraint uk_user_email unique (email)
);

create table user_role (
    role_id bigint generated by default as identity primary key,
    name    varchar(255) not null,
    user_id bigint not null,
    constraint fk_user_role_user foreign key (user_id) references "user" (user_id)
);
create index ix_user_role_user on user_role (user_id);

create table "user_otp" (
    user_otp_id         bigint generated by default as identity primary key,
    otp                 varchar(255) not null,
    expiry_date         timestamp not null,
    sent_date           timestamp,
    failed_attempts     integer not null default 0,
    resend_count        integer not null default 0,
    resend_window_start timestamp,
    user_id             bigint not null,
    constraint uk_user_otp_user unique (user_id),
    constraint fk_user_otp_user foreign key (user_id) references "user" (user_id)
);

create table "item_image" (
    item_image_id bigint generated by default as identity primary key,
    data          bytea not null,
    image_name    varchar(255),
    content_type  varchar(255) not null
);

create table "item" (
    item_id       bigint generated by default as identity primary key,
    item_name     varchar(255) not null,
    item_key      varchar(255) not null,
    item_image_id bigint,
    constraint uk_item_key unique (item_key),
    constraint fk_item_image foreign key (item_image_id) references "item_image" (item_image_id)
);

create table "item_amount" (
    item_amount_id bigint generated by default as identity primary key,
    active_date    timestamp not null,
    amount         numeric(12, 2) not null,
    item_id        bigint not null,
    constraint fk_item_amount_item foreign key (item_id) references "item" (item_id)
);
create index ix_item_amount_item on "item_amount" (item_id);

create table "order" (
    order_id           bigint generated by default as identity primary key,
    user_id            bigint not null,
    delivery_charge    numeric(12, 2) not null,
    order_date         timestamp not null,
    location_latitude  double precision not null,
    location_longitude double precision not null,
    constraint fk_order_user foreign key (user_id) references "user" (user_id)
);
create index ix_order_user on "order" (user_id);

create table "order_item" (
    order_item_id  bigint generated by default as identity primary key,
    item_qty       integer not null,
    item_amount_id bigint not null,
    order_id       bigint not null,
    constraint fk_order_item_amount foreign key (item_amount_id) references "item_amount" (item_amount_id),
    constraint fk_order_item_order foreign key (order_id) references "order" (order_id)
);
create index ix_order_item_order on "order_item" (order_id);
